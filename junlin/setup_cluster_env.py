class SetupError(RuntimeError):
    pass


def run(command, *, capture=False):
    result = subprocess.run([str(p) for p in command], text=True, capture_output=capture)
    if result.returncode:
        detail = (result.stderr or result.stdout or "").strip() if capture else "see installer output above"
        raise SetupError(f"Command failed: {shlex.join([str(p) for p in command])}\n{detail}")
    return result.stdout if capture else None


def settings(root, args, environ):
    account = environ.get("USER", "")
    account = account if account.startswith("cpsc4880_") else f"cpsc4880_{account}"
    project = args.project_dir or environ.get("ME")
    if not project:
        # A checkout under project storage identifies the account even if USER is an alias.
        project = next((p for p in root.parents if p.parent == Path("/nfs/roberts/project/cpsc4880")), None)
    if not project and not environ.get("USER"):
        raise SetupError("Cannot determine your account; pass --project-dir.")
    project = Path(project or f"/nfs/roberts/project/cpsc4880/{account}").absolute()
    shared = Path(args.shared_dir or environ.get("SHARED", "/nfs/roberts/project/cpsc4880/cpsc4880_mae73")).absolute()
    if project.resolve() == shared.resolve():
        raise SetupError("Your project directory must differ from the shared data directory.")
    gemma = environ.get("GEMMA_SERVING_PY", str(project / "envs/monitor-vllm-gemma4/bin/python"))
    qwen = shared / "envs/monitor-vllm/bin/python"
    return {
        "ME": str(project), "SHARED": str(shared), "FRAMEWORK": str(root),
        "MODELS_DIR": environ.get("MODELS_DIR", str(project / "models")),
        "ANALYSIS_PY": environ.get("ANALYSIS_PY", str(project / "envs/monitor-analysis/bin/python")),
        "GEMMA_SERVING_PY": gemma,
        "SERVING_PY": environ.get("SERVING_PY", str(qwen) if qwen.is_file() else gemma),
        "SUBMIT_PY": sys.executable, "SYSTEM_PYTHON": sys.executable,
        "HF_HOME": str(project / "cache/huggingface"), "ACCOUNT": environ.get("ACCOUNT", "cpsc4880"),
    }


def atomic_write(path, data):
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = None
    try:
        with tempfile.NamedTemporaryFile(dir=path.parent, delete=False) as stream:
            temporary = Path(stream.name)
            stream.write(data)
        temporary.replace(path)  # Replace a dangling link without writing through it.
    finally:
        if temporary and temporary.exists():
            temporary.unlink()


def save_settings(path, values):
    lines = ["# Generated by junlin/setup.sh; existing environment overrides these defaults."]
    for key, value in values.items():
        lines += [f'if [[ -z "${{{key}:-}}" ]]; then {key}={shlex.quote(value)}; fi', f"export {key}"]
    atomic_write(path, ("\n".join(lines) + "\n").encode())


def writable_private(path, values):
    path = Path(path).absolute()
    project, shared = Path(values["ME"]).resolve(), Path(values["SHARED"]).resolve()
    if path.resolve().is_relative_to(shared) or not path.resolve().is_relative_to(project):
        raise SetupError(f"Refusing to install outside your project directory: {path}")
    return path


def install(values, runner=run):
    analysis, gemma = Path(values["ANALYSIS_PY"]), Path(values["GEMMA_SERVING_PY"])
    directories = []
    for executable in (analysis, gemma):
        if executable.parts[-2:] != ("bin", "python"):
            raise SetupError(f"Use a virtual environment's bin/python: {executable}")
        directory = writable_private(executable.parent.parent, values)
        directories.append((executable, directory))
    for executable, directory in directories:
        if not executable.is_file():
            runner([values["SYSTEM_PYTHON"], "-m", "venv", directory])
        runner([executable, "-m", "ensurepip", "--upgrade"])
    runner([analysis, "-m", "pip", "install", "--index-url", "https://pypi.org/simple",
            "-r", ROOT / "requirements.txt", "-r", ROOT / "requirements-analysis.txt",
            "-r", ROOT / "requirements-download.txt"])
    runner([gemma, "-m", "pip", "install", "--index-url", "https://pypi.org/simple", "--upgrade", "uv"])
    # Official Gemma 4 CUDA 12.9 recipe, with PyPI explicit to avoid index shadowing.
    # https://docs.vllm.ai/projects/recipes/en/stable/Google/Gemma4.html
    runner([gemma.parent / "uv", "--no-config", "pip", "install", "--python", gemma,
            "--upgrade", "--pre", "vllm", "--default-index", "https://pypi.org/simple",
            "--extra-index-url", "https://wheels.vllm.ai/nightly/cu129",
            "--extra-index-url", "https://download.pytorch.org/whl/cu129",
            "--index-strategy", "unsafe-best-match"])
    runner([analysis, "-m", "pip", "check"])
    runner([gemma.parent / "uv", "--no-config", "pip", "check", "--python", gemma])


def connect_collection(entry, source, candidates, *, check=False):
    if source:
        target = Path(source).absolute()
        if not (target / entry.manifest).is_file():
            raise SetupError(f"No collection manifest: {target / entry.manifest}")
        if entry.root.is_dir() and entry.root.resolve() != target.resolve():
            raise SetupError(f"{entry.root} already points elsewhere; refusing to replace it.")
    elif (entry.root / entry.manifest).is_file():
        return
    else:
        target = next((p for p in candidates if (p / entry.manifest).is_file()), None)
    if (entry.root / entry.manifest).is_file():
        return
    if check or target is None:
        flag = "--original-rollouts" if entry.name == "original_clean" else "--control-rollouts"
        raise SetupError(f"Missing {entry.name}: {entry.root / entry.manifest}; pass {flag} DIR containing manifest.json.")
    if entry.root.exists() and not entry.root.is_symlink():
        raise SetupError(f"Refusing to replace existing directory: {entry.root}")
    if entry.root.is_symlink():
        entry.root.unlink()
    entry.root.parent.mkdir(parents=True, exist_ok=True)
    entry.root.symlink_to(target.resolve(), target_is_directory=True)


def prepare_tokenizer(registry, root, values, *, install_missing=False):
    path = registry.reference_tokenizer
    expected = json.loads((root / freeze.LOCK).read_text())["fingerprints"]["tokenizer"]
    if path.is_file():
        if hashlib.sha256(path.read_bytes()).hexdigest() != expected:
            raise SetupError(f"Reference tokenizer differs from the frozen experiment: {path}")
        return
    candidates = [Path(values["ME"]) / "models/qwen3-14b/tokenizer.json",
                  Path(values["SHARED"]) / "models/qwen3-14b/tokenizer.json"]
    source = next((p for p in candidates if p.is_file()), None)
    if not install_missing:
        raise SetupError(f"Missing reference tokenizer: {path}; run --install to copy/download the pinned file.")
    if path.parent.resolve().is_relative_to(Path(values["SHARED"]).resolve()):
        raise SetupError(f"Refusing to write a tokenizer inside shared storage: {path}")
    if source:
        data = source.read_bytes()
    else:
        actor = registry.actor
        url = f"https://huggingface.co/{actor.model_id}/resolve/{actor.revision}/tokenizer.json"
        print("Downloading only the pinned reference tokenizer (no model weights).", flush=True)
        with urlopen(url, timeout=120) as response:
            data = response.read()
    if hashlib.sha256(data).hexdigest() != expected:
        raise SetupError("Tokenizer checksum differs from the frozen experiment; original file was not changed.")
    atomic_write(path, data)


