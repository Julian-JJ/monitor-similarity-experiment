def verify(values, registry, root, runner=run):
    errors, report = [], {}
    for label, executable, code, extra in (
        ("analysis", values["ANALYSIS_PY"], ANALYSIS_CHECK, []),
        ("qwen", values["SERVING_PY"], SERVING_CHECK, ["qwen"]),
        ("gemma", values["GEMMA_SERVING_PY"], SERVING_CHECK, ["gemma"]),
    ):
        try:
            report[label] = json.loads(runner([executable, "-c", code, *extra], capture=True))
            print(f"OK {label}: {executable} {report[label]['packages']}", flush=True)
        except (SetupError, OSError, ValueError) as error:
            errors.append(f"{label} environment: {error}")
    for name in ("original_clean", "main_only_v1"):
        try:
            collection = registry.load_set(name)  # Verifies all rollout/follow-up checksums.
            report[name] = {"root": str(collection.root.resolve()), "items": len(collection.items),
                            "manifest_sha256": collection.manifest_sha256}
            if not collection.items:
                raise SetupError(f"{name} is empty")
            print(f"OK {name}: {len(collection.items)} rollouts in {collection.root.resolve()}", flush=True)
        except (RuntimeError, OSError, ValueError, KeyError) as error:
            errors.append(f"{name}: {error}")
    try:
        status, problems = freeze.check(root, registry.reference_tokenizer)
        if status != "frozen" or problems:
            raise SetupError(f"Prompt/tokenizer freeze: {status}; {'; '.join(problems)}")
    except (RuntimeError, OSError, ValueError) as error:
        errors.append(str(error))
    if errors:
        raise SetupError("Environment is not ready:\n  " + "\n  ".join(errors))
    return report


def batch_status(project):
    """Read existing artifacts only; a log file alone never implies success."""
    project = Path(project)
    run_dir, logs = project / "runs/baseline", project / "logs"
    jobs = {}
    for receipt in sorted(logs.glob("qwen-gemma-*/submissions.tsv")):
        with receipt.open() as stream:
            for row in csv.DictReader(stream, delimiter="\t"):
                if row["stage"] == "monitor":
                    jobs[row["monitor"]] = row["job_id"]
    manifest_path, metrics_path = run_dir / "manifest.json", run_dir / "metrics.json"
    manifest = json.loads(manifest_path.read_text()) if manifest_path.is_file() else {}
    metrics = json.loads(metrics_path.read_text()) if metrics_path.is_file() else {}
    # Only attribute a verdict through the run's actual cell identity.
    cells = {c["cell_id"]: c["label"]["monitor"] for c in manifest.get("cells", [])}
    records, malformed = {}, False
    items = run_dir / "items.jsonl"
    if items.is_file():
        with items.open() as stream:
            for line in stream:
                try:
                    item = json.loads(line)
                    records[item["unit_id"]] = item
                except (ValueError, KeyError):
                    malformed = True  # May be an append in progress; do not report healthy yet.
    print(f"Results: {run_dir}\nHealth requires a successful job, all 1,800 valid units and all three scored scopes.")
    out = {}
    for model in MODELS:
        job = jobs.get(model)
        status_path = logs / f"monitor-{model}-{job}.status" if job else None
        status_text = status_path.read_text() if status_path and status_path.is_file() else ""
        exits = re.findall(r"exit_code=(\d+)", status_text)
        exit_code = int(exits[-1]) if exits else None
        mine = [r for r in records.values() if cells.get(r.get("cell_id")) == model]
        valid = sum(r.get("status") == "complete" for r in mine)
        scored = [c for c in metrics.get("cells", []) if c["label"]["monitor"] == model]
        scopes = {c["label"].get("scope") for c in scored}
        scored_ok = (len(scored) == 3 and scopes == {"action", "cot", "all"}
                     and {c["cell_id"] for c in scored} == {r.get("cell_id") for r in mine}
                     and all(c["complete"] and c["units_found"] == c["units_expected"] == 600
                             and sum(r.get("cell_id") == c["cell_id"] for r in mine) == 600 for c in scored))
        healthy = exit_code == 0 and len(mine) == valid == 1800 and scored_ok and not malformed
        if healthy:
            state = "HEALTHY"
        elif exit_code not in (0, None):
            state = "FAILED"
        elif exit_code == 0 and len(mine) == 1800 and scored_ok and not malformed:
            state = "DONE_INVALID"  # Finished, with invalid verdicts; cached units are not retried.
        else:
            state = "INCOMPLETE"
        out[model] = {"state": state, "job_id": job, "exit_code": exit_code,
                      "units": len(mine), "valid_units": valid, "scored": scored_ok}
        print(f"{model:13} {state:10} job={job or 'unknown'} exit={exit_code if exit_code is not None else 'unknown'} "
              f"units={len(mine)}/1800 valid={valid} scored={'yes' if scored_ok else 'no'}")
        if state != "HEALTHY" and job:
            print(f"  {logs / f'monitor-server-{model}-{job}.log'}")
    qwen_healthy = all(out[m]["state"] == "HEALTHY" for m in MODELS[:2])
    print("Both Qwen jobs completed healthily." if qwen_healthy else "Both Qwen jobs are NOT yet confirmed healthy.")
    print("For current queued/running states: squeue --me")
    return out


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--install", action="store_true")
    mode.add_argument("--check", action="store_true")
    mode.add_argument("--status", action="store_true")
    for name in ("project-dir", "shared-dir", "original-rollouts", "control-rollouts"):
        parser.add_argument("--" + name, type=Path)
    args = parser.parse_args(argv)
    try:
        values = settings(ROOT, args, os.environ)
        if args.status:
            batch_status(values["ME"])
            return 0
        registry = Registry.load(root=ROOT)
        for name, source, directory in (("original_clean", args.original_rollouts, "rollouts_original_clean"),
                                         ("main_only_v1", args.control_rollouts, "rollouts_main_only_clean")):
            connect_collection(registry.sets[name], source,
                               [Path(values["ME"]) / directory, Path(values["SHARED"]) / directory], check=args.check)
        prepare_tokenizer(registry, ROOT, values, install_missing=args.install)
        if args.install:
            install(values)
        report = verify(values, registry, ROOT)
        if not args.check:
            for directory in (values["MODELS_DIR"], str(Path(values["ME"]) / "logs"), values["HF_HOME"]):
                writable_private(directory, values).mkdir(parents=True, exist_ok=True)
            report_path = Path(values["ME"]) / "logs" / ("cluster-env-" + datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ") + f"-{os.getpid()}.json")
            report.update(settings=values, checked_at=datetime.now(timezone.utc).isoformat(),
                          gpu_inference_tested=False)
            atomic_write(report_path, (json.dumps(report, indent=2) + "\n").encode())
            save_settings(ROOT / ".env.cluster", values)
            print(f"Saved settings: {ROOT / '.env.cluster'}\nVerification report: {report_path}")
        print(f"READY: results will go to {values['ME']}/runs/baseline/")
        print("CPU checks passed; GPU kernel execution and model inference are tested by the monitor jobs.")
    except (SetupError, OSError, RuntimeError, ValueError, KeyError) as error:
        print(f"ERROR: {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
